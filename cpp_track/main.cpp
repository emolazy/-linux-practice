#include <iostream>

int main() {
    int choice; // Переменная для выбора пользователя

    std::cout << "=== АВТОМАТ С НАПИТКАМИ ===" << std::endl;
    std::cout << "1 - Вода" << std::endl;
    std::cout << "2 - Кола" << std::endl;
    std::cout << "3 - Сок" << std::endl;
    std::cout << "Выберите номер напитка: ";
    
    // Читаем выбор пользователя
    std::cin >> choice; 

    // --- ТВОЙ КОД НАЧИНАЕТСЯ ЗДЕСЬ ---

    if (choice == 1) {
        std::cout << "Вы получли воду." << std::endl;
    } else if (choice == 2) {
        std::cout << "Вы получили Колу" << std::endl;
    } else if (choice == 3) {
        std::cout << "Вы получили сок" << std::endl;
    } else {
        std::cout << "Такого напитка нет" << std::endl;
    }
    // 1. Если choice равен 1, выведи "Вы получили Воду."
    // 2. Если choice равен 2, выведи "Вы получили Колу."
    // 3. Если choice равен 3, выведи "Вы получили Сок."
    // 4. Иначе (если ввели 4, 5, 0 или букву), выведи "Ошибка: такого напитка нет."

    // --- ТВОЙ КОД ЗАКАНЧИВАЕТСЯ ЗДЕСЬ ---

    return 0;
}