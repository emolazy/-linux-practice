#!/bin/bash

# 1. ПЕРЕМЕННЫЕ
DATE=$(date +%Y-%m-%d)
BACKUP_NAME="backup_$DATE.tar.gz"

echo "--- Начинаю резервное копирование ---"

# 2. ЦИКЛ (просто для примера, чтобы показать, как он работает)
# Мы просто выведем список файлов, которые будем архивировать
for FILE in *.txt *.sh; do
    if [ -f "$FILE" ]; then
        echo "Найден файл: $FILE"
    fi
done

# 3. Создание архива
# Ключи: c - создать, z - сжать (gzip), f - имя файла архива
tar -czf "$BACKUP_NAME" ./*

# 4. ПРОВЕРКА (условие и exit code)
# $? — это код возврата последней команды. 0 означает успех.
if [ $? -eq 0 ]; then
    echo "УСПЕХ! Архив создан: $BACKUP_NAME"
else
    echo "ОШИБКА! Не удалось создать архив."
    exit 1  # Выход с кодом ошибки
fi

echo "--- Резервное копирование завершено ---"
